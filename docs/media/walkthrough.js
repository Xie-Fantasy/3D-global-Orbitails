// Replay with playwright-cli run-code --filename docs/media/walkthrough.js.
// Use a 1920 x 1080 viewport, ready React demo, daytime, English, rotation off.
async page => {
  await page.bringToFront()
  const started = Date.now()
  const chapters = []
  const chapter = title => chapters.push({ seconds: (Date.now() - started) / 1000, title })
  const pause = ms => page.waitForTimeout(ms)
  const button = name => page.getByRole("button", { name, exact: true })
  chapter("Global network / daytime Earth")
  await pause(1700)
  chapter("Pointer-directed zoom")
  await page.mouse.move(1120, 480)
  await page.mouse.wheel(0, -110)
  await pause(1100)
  await page.mouse.wheel(0, 110)
  await pause(1000)
  chapter("Bars and route layers")
  await button("Bars OFF").click()
  await pause(1100)
  await button("Flight arcs ON").click()
  await pause(900)
  await button("Flight arcs OFF").click()
  await pause(900)
  chapter("Nighttime / deep blue")
  await button("Nighttime NIGHT").click()
  await button("Deep blue").click()
  await pause(2300)
  chapter("Nebula violet / custom styling")
  await button("Nebula violet").click()
  await pause(1600)
  chapter("Amber / procedural grid")
  await button("Amber gold").click()
  await button("No texture GRID").click()
  await pause(1600)
  chapter("Particle and star density")
  await page.getByRole("slider", { name: "Particle halo", exact: true }).fill("240")
  await page.getByRole("slider", { name: "Deep-space stars", exact: true }).fill("240")
  await pause(1400)
  chapter("English and Chinese")
  await button("中文").click()
  await pause(1400)
  await button("EN").click()
  await button("Emerald").click()
  await button("Daytime DAY").click()
  await pause(1200)
  chapter("Node selection and focus")
  const label = page.locator('.globe-label[data-location-id="gz"]')
  const box = await label.boundingBox()
  if (box) {
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await pause(450)
    await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2)
    await pause(1800)
    await page.keyboard.press("Escape")
  }
  await button("Reset view RESET").click()
  await page.mouse.move(960, 540)
  await page.mouse.wheel(0, 180)
  await pause(1300)
  chapter("Country focus / geographic boundaries")
  await page.mouse.click(1030, 450)
  await pause(1700)
  await page.keyboard.press("Escape")
  chapter("Drag / globe navigation")
  await page.mouse.move(950, 650)
  await page.mouse.down()
  for (let index = 1; index <= 26; index++) {
    await page.mouse.move(950 + index * 7, 650 - index * 2)
    await pause(18)
  }
  await page.mouse.up()
  await pause(900)
  chapter("Vue implementation")
  await page.goto("http://127.0.0.1:5174/?quality=medium")
  await button("Rotating ON").waitFor({ state: "visible" })
  await button("Rotating ON").click()
  await page.mouse.move(960, 540)
  await page.mouse.wheel(0, 180)
  await pause(1700)
  await button("Nighttime NIGHT").click()
  await pause(1800)
  chapter("End")
  return { duration: (Date.now() - started) / 1000, chapters }
}
